export function t(key: string, lang: Language = "he", vars?: Record<string, string | number>): string {
  const raw = DICTS[lang]?.[key] ?? DICTS.he[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`));
}

export function isRtl(lang: Language): boolean {
  return lang === "he";
}
